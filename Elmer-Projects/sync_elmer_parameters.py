def write_parameter_summary(model: dict) -> None:
    rows: list[dict[str, str]] = []
    params = model["parameters"]
    exprs = model["parameter_expressions"]
    unit_pattern = re.compile(r"\[\s*([a-zA-Z0-9/^*()\-]+)\s*\]")

    def unit_of(name: str) -> str:
        match = unit_pattern.search(str(exprs.get(name, "")))
        return match.group(1) if match else ""

    for name, value in params.items():
        rows.append(
            {
                "category": "parameter",
                "name": name,
                "value": fmt(value),
                "unit": unit_of(name),
                "expression": exprs.get(name, ""),
                "note": "",
            }
        )

    for mat_name, mat in model["materials"].items():
        for key in ("k", "rho", "cp"):
            nominal = mat[key].get("nominal")
            rows.append(
                {
                    "category": f"material:{mat_name}",
                    "name": key,
                    "value": fmt(nominal) if nominal is not None else "",
                    "unit": "",
                    "expression": mat[key]["expression"],
                    "note": "" if nominal is not None else "temperature-dependent",
                }
            )

    for name, value in model.get("elmer_overrides", {}).items():
        rows.append(
            {
                "category": "elmer_override",
                "name": name,
                "value": fmt(value),
                "unit": "",
                "expression": "",
                "note": "",
            }
        )

    for case_name, case_values in model.get("cases", {}).items():
        for name, value in case_values.items():
            rows.append(
                {
                    "category": f"case:{case_name}",
                    "name": name,
                    "value": json.dumps(value) if isinstance(value, (list, dict)) else fmt(value),
                    "unit": "",
                    "expression": "",
                    "note": "",
                }
            )

    out_path = GENERATED_DIR / "tes_parameter_summary.csv"
    with out_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f, fieldnames=["category", "name", "value", "unit", "expression", "note"]
        )
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    import sys

    args = sys.argv[1:]
    if args:
        set_params_json((ROOT / args[0]).resolve() if not Path(args[0]).is_absolute() else Path(args[0]))

    model = load_model()
    GENERATED_DIR.mkdir(exist_ok=True)

    (GENERATED_DIR / "tes_shared_variables.sif").write_text(
        build_shared_variables(model),
        encoding="utf-8",
    )
    (GENERATED_DIR / "tes_materials.sif").write_text(
        build_materials_include(model),
        encoding="utf-8",
    )

    from scripts.support.build_cases import build_all_cases

    written = build_all_cases(model, GENERATED_DIR / "cases", ROOT)
    print(f"generated/cases: {', '.join(written)}")

    write_parameter_summary(model)


if __name__ == "__main__":
    main()
