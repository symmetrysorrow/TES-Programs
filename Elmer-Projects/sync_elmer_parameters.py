ROOT = Path(__file__).resolve().parent
PARAMS_JSON = ROOT / "elmer_project.json"
GENERATED_DIR = ROOT / "generated"


def fmt(value: object) -> str:
    if isinstance(value, float):
        return f"{value:.16g}"
    return str(value)


def load_model() -> dict:
    """Load elmer_project.json and derive all numeric fields from their
    expressions (expressions-only schema). The file is never modified; a
    numeric value stored alongside an expression is legacy and gets flagged."""
    model = json.loads(PARAMS_JSON.read_text(encoding="utf-8"))
    reconciled = reconcile_project(model)
    drift = numeric_drift_report(model, reconciled)
    if drift:
        print(f"WARNING: {PARAMS_JSON.name} has numeric fields that contradict their expressions")
        print("         (expressions win; delete the stored numbers):")
        for line in drift:
            print(f"  {line}")
    return reconciled


def set_params_json(path: Path) -> None:
    global PARAMS_JSON
    PARAMS_JSON = path


def matc_temperature_expr(expr: str) -> str:
    expr = re.sub(r"\bT\b", "tx", expr)
    return expr.replace("**", "^")


def membrane_conductivity_at_t0(model: dict) -> float:
    params = model["parameters"]
    membrane_expr = str(model["materials"]["Membrane"]["k"]["expression"])
    python_expr = membrane_expr.replace("^", "**")
    values = {name: float(value) for name, value in params.items()}
    values["T"] = float(params["T_0"])
    return float(eval(python_expr, {"__builtins__": {}}, values))


def membrane_matc_expr(model: dict) -> str:
    membrane_expr = str(model["materials"]["Membrane"]["k"]["expression"])
    # Guard the non-integer power law against negative or zero iterates in
    # the nonlinear solve while preserving the original k(T) for T > 0.
    t_guard = "(0.5*((tx+1.0e-12)+abs(tx-1.0e-12)))"
    guarded_expr = re.sub(r"\bT\b", t_guard, membrane_expr)
    return guarded_expr.replace("**", "^")


